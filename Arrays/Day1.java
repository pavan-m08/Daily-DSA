public class Day1 {
    public static void main(String[] args) {

        // Create an array of 5 integers
        int[] numbers = {10, 20, 30, 40, 50};

        // Print each element using a for loop
        for (int i = 0; i < numbers.length; i++) {
            System.out.println(numbers[i]);
        }
    }
}